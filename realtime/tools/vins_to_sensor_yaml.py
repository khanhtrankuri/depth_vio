#!/usr/bin/env python3
"""Write EuRoC/Kalibr-style cam0/cam1 sensor.yaml files (what the depth node reads) from a VINS-Fusion config.

Takes intrinsics/distortion from the PINHOLE camera files named by cam0_calib / cam1_calib and T_BS from
body_T_cam0 / body_T_cam1 of the main VINS yaml. Only pinhole + radtan is supported (same as the depth node).

    python3 vins_to_sensor_yaml.py thermal_stereo_imu_config.yaml [out_dir]
-> out_dir/cam0_sensor.yaml, out_dir/cam1_sensor.yaml (default out_dir: next to the VINS yaml)
"""
import sys
from pathlib import Path

import cv2
import numpy as np


def read_fs(path):
    fs = cv2.FileStorage(str(path), cv2.FILE_STORAGE_READ)
    if not fs.isOpened():
        raise SystemExit(f'cannot read {path}')
    return fs


def cam_entry(cfg_dir, fs_main, i):
    calib = Path(cfg_dir) / fs_main.getNode(f'cam{i}_calib').string()
    fc = read_fs(calib)
    model = fc.getNode('model_type').string()
    if model.upper() != 'PINHOLE':
        raise SystemExit(f'{calib}: model_type {model} is not PINHOLE (the depth node only handles pinhole + radtan)')
    pp, dp = fc.getNode('projection_parameters'), fc.getNode('distortion_parameters')
    K = [pp.getNode(k).real() for k in ('fx', 'fy', 'cx', 'cy')]
    D = [dp.getNode(k).real() for k in ('k1', 'k2', 'p1', 'p2')]
    wh = [int(fc.getNode('image_width').real()), int(fc.getNode('image_height').real())]
    T = fs_main.getNode(f'body_T_cam{i}').mat()
    if T is None or T.shape != (4, 4):
        raise SystemExit(f'body_T_cam{i} missing or not 4x4')
    return calib, K, D, wh, T


def main():
    cfg = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else cfg.parent
    fs = read_fs(cfg)
    for i in (0, 1):
        calib, K, D, wh, T = cam_entry(cfg.parent, fs, i)
        f = out / f'cam{i}_sensor.yaml'
        T_flat = ', '.join(f'{v:.10g}' for v in T.reshape(-1))
        f.write_text(
            f'# generated by vins_to_sensor_yaml.py from {cfg.name} + {calib.name}\n'
            f'sensor_type: camera\n'
            f'T_BS:\n  rows: 4\n  cols: 4\n  data: [{T_flat}]\n'
            f'resolution: [{wh[0]}, {wh[1]}]\n'
            f'camera_model: pinhole\n'
            f'intrinsics: [{", ".join(f"{v:.10g}" for v in K)}]\n'
            f'distortion_model: radial-tangential\n'
            f'distortion_coefficients: [{", ".join(f"{v:.10g}" for v in D)}]\n')
        print('wrote', f)
    T0, T1 = fs.getNode('body_T_cam0').mat(), fs.getNode('body_T_cam1').mat()
    print(f'stereo baseline |t_cam1 - t_cam0| = {np.linalg.norm(T1[:3, 3] - T0[:3, 3]) * 100:.2f} cm')


if __name__ == '__main__':
    main()
